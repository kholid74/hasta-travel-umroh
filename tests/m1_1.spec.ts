test("Hajj validation, shared payments and contract snapshots preserve financial records", () => {
  const state = createSeed(), p = state.hajjPackages[0];
  expect(hajjPrice(p)).toBe(200000000);
  expect(hajjPrice({ currency: "USD", sellingPrice: "0.10", exchangeRate: "16000.123456" })).toBe(1600);
  for (const patch of [{ capacity: 0 }, { capacity: NaN }, { departureYear: 2025 }, { departureDate: "2029-01-01" }, { assumptionDate: "2026-02-30" }, { exchangeRate: "" }, { exchangeRate: "0" }, { sellingPrice: "-1" }, { milestones: [{ name: "Tahap", percent: 99 }] }, { requirements: ["Paspor", "Paspor"] }, { inclusions: ["Hotel", "Hotel"] }, { requirements: ["__proto__"] }]) {
    expect(() => validateHajjPackage({ ...p, ...patch })).toThrow();
  }
  const j = newJamaah("JMH-TEST", "Jamaah Uji Haji", "08000000999");
  state.jamaah.push(j);
  const b = registerHajj(state, p.id, j.id), contract = structuredClone(b);
  expect(b.productType).toBe("HAJJ_SPECIAL");
  expect(b.departureId).toBe("");
  expect(paymentStatus(state, b)).toBe("Belum bayar");
  expect(packageForBooking(state, b)?.id).toBe(p.id);
  expect(() => registerHajj(state, p.id, j.id)).toThrow();
  expect(() => saveHajjPackage(state, { ...p, capacity: 2 })).toThrow();
  saveHajjPackage(state, { ...p, sellingPrice: "15000", exchangeRate: "17000", requirements: [...p.requirements, "Persetujuan layanan demo"] });
  expect(b).toEqual(contract);
  expect(j.documents["Persetujuan layanan demo"]).toBe("Belum ada");
  recordPayment(state, b.id, 10000000, "Transfer demo");
  verifyPayment(state, state.payments[0].id);
  expect(outstanding(state, b)).toBe(190000000);
  expect(paymentStatus(state, b)).toBe("Cicilan");
  state.hajjPackages[0].status = "Closed";
  expect(() => registerHajj(state, p.id, state.jamaah[0].id)).toThrow();
});

test("Hajj HPP exact totals, exchange assumptions, saved revisions and browser encoding", () => {
  const state = createSeed(), p = state.hajjPackages[0], c = latestCosting(state, p.id)!;
  const result = calculateCosting(c);
  expect(result.variable).toBe(BigInt(13640000000));
  expect(result.fixed).toBe(BigInt(16500000000));
  expect(result.total).toBe(BigInt(425700000000));
  expect(result.revenue).toBe(BigInt(600000000000));
  expect(result.profit).toBe(BigInt(174300000000));
  expect(result.hpp).toBe(BigInt(14190000000));
  expect(result.margin).toBe(BigInt(2905));
  saveCosting(state, c.id, c, true);
  const snapshot = structuredClone(c);
  const revision = reviseCosting(state, c.id);
  saveCosting(state, revision.id, { ...revision, assumptionDate: "2026-11-03", payingCount: 20, items: revision.items.map(i => i.currency === "SAR" ? { ...i, exchangeRate: "4500" } : i) }, true);
  expect(c).toEqual(snapshot);
  expect(calculateCosting(revision).total).toBe(BigInt(294900000000));
  expect(() => saveCosting(state, c.id, revision)).toThrow();
  const restored = decodeDemo(encodeDemo(state));
  expect(restored).toEqual(state);
  expect(restored.costings.find(v => v.id === c.id)).toEqual(snapshot);
  const newPackage = { ...state.hajjPackages[1], id: "HAJ-NEW" };
  saveHajjPackage(state, newPackage);
  expect(newCosting(state, newPackage.id).items.some(i => i.category === "Kontingensi")).toBeTruthy();
  for (const payingCount of [0, -1, NaN, Infinity]) expect(() => calculateCosting({ ...c, payingCount })).toThrow();
  expect(() => calculateCosting({ ...c, assumptionDate: "" })).toThrow();
  expect(() => decodeDemo("broken")).toThrow(/Reset/);
  expect(() => decodeDemo(JSON.stringify({ version: 99, state }))).toThrow(/Reset/);
  expect(() => decodeDemo(encodeDemo({ ...state, jamaah: [] }))).toThrow(/Reset/);
  expect(createSeed().costings.find(v => v.id === c.id)?.status).toBe("Draft");
});

