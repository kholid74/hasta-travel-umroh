test("corrupt storage requires explicit reset and failed storage writes do not save", async ({ page }) => {
  await login(page);
  await page.evaluate(key => localStorage.setItem(key, "invalid JSON"), DEMO_STORAGE_KEY);
  await page.reload();
  await expect(page.locator(".form-error")).toContainText("tidak dapat dibaca");
  expect(await page.evaluate(key => localStorage.getItem(key), DEMO_STORAGE_KEY)).toBe("invalid JSON");
  page.once("dialog", d => d.accept());
  await page.getByRole("button", { name: "Reset data demo", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Selamat pagi, Ahmad" })).toBeVisible();
  await page.goto("/admin/haji-khusus");
  await page.evaluate(() => { Storage.prototype.setItem = () => { throw new DOMException("Quota exceeded", "QuotaExceededError"); }; });
  await page.getByRole("button", { name: "Buat paket Haji", exact: true }).click();
  await page.getByRole("dialog").getByLabel("Nama paket Haji").fill("Paket Gagal Tersimpan Demo");
  await page.getByRole("dialog").getByRole("button", { name: "Simpan paket Haji", exact: true }).click();
  await expect(page.locator(".admin-toast.error")).toContainText("penyimpanan browser penuh atau diblokir");
  await expect(page.getByRole("dialog")).toBeVisible();
  await page.reload();
  await expect(page.locator("tbody")).not.toContainText("Paket Gagal Tersimpan Demo");
});
